export type Cle = keyof typeof TEXTES;

export function traduire(lg: Langue, cle: Cle, valeurs?: Record<string, string | number>): string {
  const [fr, en] = TEXTES[cle];
  let texte: string = lg === "en" ? en : fr;
  if (valeurs) for (const [k, v] of Object.entries(valeurs)) texte = texte.split(`{${k}}`).join(String(v));
  return texte;
}

/** Remplace `{nom}` dans un libellé venu du serveur (libellés du rapport). */
export function formater(texte: string, valeurs: Record<string, string | number>): string {
  for (const [k, v] of Object.entries(valeurs)) texte = texte.split(`{${k}}`).join(String(v));
  return texte;
}

export const LangueContext = createContext<Langue>("fr");

export function useT() {
  const lg = useContext(LangueContext);
  return (cle: Cle, valeurs?: Record<string, string | number>) => traduire(lg, cle, valeurs);
}

export function useLangue() {
  return useContext(LangueContext);
}
